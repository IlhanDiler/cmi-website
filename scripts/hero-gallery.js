let heroIndex = 0;
const heroSlideDuration = 6500;
const heroFadeDuration = 1400;
const heroInteractionPauseDuration = 12000;
let fadeToggle = false;
let isFading = false;
let isHeroGalleryPaused = false;
let hasHeroGalleryAutoplayOverride = false;
